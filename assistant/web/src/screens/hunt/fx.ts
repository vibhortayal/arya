export const QFX = { on: false, ctx: null as AudioContext | null };
try { QFX.on = localStorage.getItem("arya-sound") === "1"; } catch { /* off */ }

export function setSound(on: boolean) {
  QFX.on = on;
  try { localStorage.setItem("arya-sound", on ? "1" : "0"); } catch { /* blocked */ }
  if (on) qTone([660, 880], 0.07);
}

/* Retro blips generated by Web Audio: square waves, no files. */
export function qTone(freqs: number[], step: number) {
  if (!QFX.on) return;
  try {
    const AC = window.AudioContext || (window as any).webkitAudioContext;
    if (!AC) return;
    QFX.ctx = QFX.ctx || new AC();
    const ctx = QFX.ctx!, t0 = ctx.currentTime + 0.01;
    freqs.forEach((f, i) => {
      const o = ctx.createOscillator(), g = ctx.createGain();
      o.type = "square"; o.frequency.value = f;
      const t = t0 + i * step;
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(0.06, t + 0.01);
      g.gain.exponentialRampToValueAtTime(0.0001, t + step * 0.95);
      o.connect(g).connect(ctx.destination);
      o.start(t); o.stop(t + step);
    });
  } catch { /* sound is garnish */ }
}
export function qBuzz(pattern: number | number[]) {
  if (QFX.on && navigator.vibrate) { try { navigator.vibrate(pattern); } catch { /* no buzz */ } }
}
export function qFloat(text: string, anchorSel: string) {
  const at = document.querySelector(anchorSel);
  if (!at) return;
  const r = at.getBoundingClientRect();
  const el = document.createElement("span");
  el.className = "ptfloat";
  el.textContent = text;
  el.style.left = `${Math.round(r.left + r.width / 2)}px`;
  el.style.top = `${Math.round(r.top)}px`;
  document.body.appendChild(el);
  setTimeout(() => el.remove(), 1200);
}
function qBumpHud() {
  const c = document.getElementById("hunt-pts");
  if (!c) return;
  c.classList.remove("bump"); void c.offsetWidth; c.classList.add("bump");
}

/* [share of the list, en.json key]. */
const QMILESTONES: [number, string][] = [[0.5, "hunt.fx.halfway"]];
let qMilestoneTimer = 0;
export function qShowMilestone(text: string) {
  const m = document.getElementById("milestone");
  if (!m) return;
  m.textContent = text;
  m.classList.remove("show"); void m.offsetWidth; m.classList.add("show");
  clearTimeout(qMilestoneTimer);
  qMilestoneTimer = window.setTimeout(() => { m.classList.remove("show"); }, 2400);
}

/* The combo is a count, not a clock. */
export function qComboAfter(prev: number, wasSuggested: boolean): number {
  const n = Number(prev) > 0 ? Math.floor(Number(prev)) : 0;
  return n + (wasSuggested ? 1 : 0);
}

/* One grab's reward. Quest mode only; nothing here can fail a hunt. */
export function qRewardGrab(sess: Session, before: number, opts: { wasSuggested: boolean; boss: boolean }) {
  if (!sess || sess.mode !== "quest") return;
  const p = qProgress(sess);
  Q.combo = qComboAfter(Q.combo || 0, opts.wasSuggested);
  qFloat(`+${QPTS.item}`, "#hunt-pts");
  if (opts.boss) qFloat(t("hunt.fx.boss", { pts: QPTS.boss }), "#hunt-count");
  qBumpHud();
  qBuzz(15);
  if (p.total && p.done === p.total) {
    qFloat(t("hunt.fx.fullHaul", { pts: QPTS.haul }), "#hunt-count");
    qShowMilestone(t("hunt.fx.allCollected"));
    qConfetti();
    qTone([523, 659, 784, 1047], 0.11);
    qBuzz([30, 60, 30, 60, 80]);
    return;
  }
  const crossed = QMILESTONES.filter(([f]) => before < p.total * f && p.done >= p.total * f).pop();
  if (crossed) {
    qShowMilestone(t(crossed[1]));
    qTone([587, 740, 880], 0.08);
  } else if (p.total > 2 && p.total - p.done === 1) {
    qShowMilestone(t("hunt.fx.oneToGo"));
    qTone([587, 740, 880], 0.08);
  } else {
    qTone([660, 880], 0.06);
  }
}

/* Confetti on one fixed canvas, ~1.8 s. Reduced motion skips it. */
export function qConfetti() {
  const cv = document.getElementById("confetti") as HTMLCanvasElement | null;
  if (!cv || !cv.getContext) return;
  if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  const W = window.innerWidth, H = window.innerHeight;
  cv.width = W * dpr; cv.height = H * dpr;
  cv.hidden = false;
  const g = cv.getContext("2d");
  if (!g) return;
  g.setTransform(dpr, 0, 0, dpr, 0, 0);
  const colors = ["#E4572E", "#E4572E", "#FDEEE8", "#1B1B1E", "#8B8B93", "#FFFFFF"];
  const bits = Array.from({ length: 120 }, () => ({
    x: W / 2 + (Math.random() - 0.5) * W * 0.3, y: H * 0.35,
    vx: (Math.random() - 0.5) * 9, vy: -Math.random() * 11 - 4,
    w: 5 + Math.random() * 6, h: 3 + Math.random() * 4,
    a: Math.random() * Math.PI, va: (Math.random() - 0.5) * 0.3,
    c: colors[Math.floor(Math.random() * colors.length)],
  }));
  const t0 = performance.now();
  let last = t0;
  function frame(now: number) {
    const dt = Math.min(2, (now - last) / (1000 / 60));
    last = now;
    g!.clearRect(0, 0, W, H);
    for (const b of bits) {
      b.vy += 0.32 * dt; b.vx *= 0.99;
      b.x += b.vx * dt; b.y += b.vy * dt; b.a += b.va * dt;
      g!.save(); g!.translate(b.x, b.y); g!.rotate(b.a);
      g!.fillStyle = b.c; g!.fillRect(-b.w / 2, -b.h / 2, b.w, b.h);
      g!.restore();
    }
    if (now - t0 < 1800) requestAnimationFrame(frame);
    else if (cv) { g!.clearRect(0, 0, W, H); cv.hidden = true; }
  }
  requestAnimationFrame(frame);
}

/* ---- The celebration (Discussion 32): the item as its character with
 * one fun fact. DISABLED at the owner's word (phone pass, 2026-10-28),
 * as in quest.js qOnCollected; re-enabling is CELEBRATE = true. ---- */
const CELEBRATE = false;
let CELEB: Manifest | null = null;
let celebTimer = 0;
export function qCelebLoad() {
  if (CELEB) return;
  characterManifest().then(m => { if (m) CELEB = m; }).catch(() => {});
}
function celebMatch(tokens: string[], kw: string) {
  const kt = kw.split(" ");
  for (let i = 0; i + kt.length <= tokens.length; i++) if (kt.every((w, j) => tokens[i + j] === w)) return true;
  return false;
}
type Rule = { keywords?: string[]; char?: string; fact?: string };
export function qCelebResolve(name: string, manifest: Manifest | null) {
  if (!manifest) return null;
  const tokens = qnorm(name).split(" ").filter(Boolean);
  let item: Rule | null = null, cat: Rule | null = null;
  for (const r of (manifest.items || []) as Rule[]) if (!item && (r.keywords || []).some(k => celebMatch(tokens, k))) item = r;
  for (const c of (manifest.categories || []) as Rule[]) if (!cat && (c.keywords || []).some(k => celebMatch(tokens, k))) cat = c;
  const char = (item && item.char) || (cat && cat.char) || null;
  const fact = (item && item.fact) || (cat && cat.fact) || null;
  if (!char && !fact) return null;
  return { char, fact };
}
export function qCelebHide() {
  if (celebTimer) { clearTimeout(celebTimer); celebTimer = 0; }
  const layer = document.getElementById("celeb-layer");
  if (layer) { layer.hidden = true; layer.replaceChildren(); }
}
export function qOnCollected(name: string) {
  if (!CELEBRATE) return;
  const hit = qCelebResolve(name, CELEB);
  const layer = document.getElementById("celeb-layer");
  if (!hit || !layer) return;
  if (celebTimer) clearTimeout(celebTimer);
  layer.replaceChildren();
  if (hit.char) {
    const img = document.createElement("img");
    img.className = "celeb-char"; img.alt = ""; img.src = "/assets/characters/" + (hit.char || faceFor(name));
    layer.appendChild(img);
  }
  if (hit.fact) {
    const b = document.createElement("div");
    b.className = "celeb-bubble"; b.textContent = hit.fact;
    layer.appendChild(b);
  }
  layer.hidden = false;
  celebTimer = window.setTimeout(qCelebHide, 3500);
}
